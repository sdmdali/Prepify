"use strict";
const tests = require("../repositories/test.repository");
const questions = require("../repositories/question.repository");
const catalog = require("../repositories/catalog.repository");
const { withTransaction } = require("../config/database");
const { E } = require("../utils/errors");
const ai = require("./ai.service");
const questionService = require("./question.service");

async function assertQuestionsExist(ids, conn) {
  const unique = [...new Set(ids)];
  if (unique.length !== ids.length)
    throw E.validation([
      { field: "questionIds", message: "Duplicate question ids" },
    ]);
  const found = new Set(await tests.existingQuestionIds(unique, conn));
  const missing = unique.filter((i) => !found.has(i));
  if (missing.length)
    throw E.validation([
      {
        field: "questionIds",
        message: `Unknown question ids: ${missing.join(", ")}`,
      },
    ]);
}

async function create(user, body) {
  if (body.subjectId && !(await catalog.getSubject(body.subjectId)))
    throw E.validation([
      { field: "subjectId", message: "Subject does not exist" },
    ]);
  const id = await withTransaction(async (conn) => {
    if (body.questionIds?.length)
      await assertQuestionsExist(body.questionIds, conn);
    const tid = await tests.insert(conn, {
      ...body,
      status: "draft",
      userId: user.id,
    });
    if (body.questionIds?.length)
      await tests.replaceQuestions(conn, tid, body.questionIds);
    return tid;
  });
  return tests.present(await tests.getRaw(id));
}

async function assignQuestions(testId, questionIds) {
  const t = await tests.getRaw(testId);
  if (!t) throw E.notFound("Test not found");
  if (t.status !== "draft")
    throw E.conflict(
      "Questions can only be changed while the test is a draft",
      "TEST_NOT_DRAFT",
    );
  await withTransaction(async (conn) => {
    await assertQuestionsExist(questionIds, conn);
    await tests.replaceQuestions(conn, testId, questionIds);
  });
  return tests.present(await tests.getRaw(testId));
}

async function publish(testId) {
  const t = await tests.getRaw(testId);
  if (!t) throw E.notFound("Test not found");
  if (t.status === "published") return tests.present(t);
  if (t.status === "archived")
    throw E.conflict("Archived tests cannot be published", "TEST_ARCHIVED");
  if (Number(t.question_count) === 0)
    throw E.conflict(
      "A test needs at least one question before publishing",
      "TEST_EMPTY",
    );
  await tests.setStatus(testId, "published");
  return tests.present(await tests.getRaw(testId));
}

async function archive(testId) {
  if (!(await tests.getRaw(testId))) throw E.notFound("Test not found");
  await tests.setStatus(testId, "archived");
  return tests.present(await tests.getRaw(testId));
}

async function list(user, f) {
  const { items, total } = await tests.list(user, {
    ...f,
    offset: (f.page - 1) * f.limit,
  });
  return { items, page: f.page, limit: f.limit, total };
}

async function get(user, id) {
  const t = await tests.getRaw(id);
  // 404 (not 403) so students cannot probe for the existence of hidden tests.
  if (!t || !tests.canView(user, t)) throw E.notFound("Test not found");
  return tests.present(t);
}

/**
 * Practice tests are generated by AI on demand. The question table stores generated
 * questions for review/history, but pre-imported question-bank rows are never used
 * to fill a practice test.
 */
async function generatePractice(user, b) {
  let subject = b.subjectId ? await catalog.getSubject(b.subjectId) : null;
  const syllabusText = String(b.syllabusText || "").trim();
  const requestedTopic = String(b.topic || "").trim();
  const requestedCount = Number(b.questionCount);

  if (!subject && syllabusText && !b.subjectId) {
    subject = await catalog.getSubjectBySlug("uploaded-syllabus");
    if (!subject) {
      try {
        subject = await catalog.createSubject({ slug: "uploaded-syllabus", name: "Uploaded Syllabus" });
      } catch (err) {
        subject = await catalog.getSubjectBySlug("uploaded-syllabus");
        if (!subject) throw err;
      }
    }
  }
  if (!subject) throw E.validation([{ field: "subjectId", message: "Choose a valid subject or upload a syllabus PDF" }]);

  // The free-text topic is intentionally a strict focus only when a PDF is supplied.
  // Subject-only practice covers the full subject even if a topic field was typed.
  let topicName = syllabusText && requestedTopic ? requestedTopic : undefined;
  let topicId = null;
  if (topicName) {
    let topic = await catalog.getTopicByName(subject.id, topicName);
    if (!topic) topic = await catalog.createTopic(subject.id, topicName);
    topicId = Number(topic.id);
  } else if (syllabusText) {
    let topic = await catalog.getTopicByName(subject.id, "Uploaded Syllabus");
    if (!topic) topic = await catalog.createTopic(subject.id, "Uploaded Syllabus");
    topicId = Number(topic.id);
  }

  const generated = await ai.generateQuestions(user.id, {
    subjectName: subject.name,
    ...(topicName && syllabusText ? { topic: topicName } : {}),
    ...(syllabusText ? { syllabusText } : {}),
    difficulty: b.difficulty,
    count: requestedCount,
  });
  if (!Array.isArray(generated?.questions) || generated.questions.length !== requestedCount) {
    throw E.badGateway("AI did not generate the requested number of usable questions. Please try again.", "AI_INSUFFICIENT_QUESTIONS");
  }

  // Persist AI-created questions, then attach these exact IDs to this test. Do not
  // select random pre-existing bank questions after generation.
  const ids = await questionService.saveMany(user, {
    subjectId: subject.id,
    ...(topicId ? { topicId } : {}),
    questions: generated.questions,
    source: "AI",
  });
  const uniqueIds = [...new Set(ids.map(Number))];
  if (uniqueIds.length !== requestedCount) {
    throw E.conflict("AI returned duplicate questions. Please generate the practice test again.", "AI_DUPLICATE_QUESTIONS");
  }

  const titleScope = syllabusText && requestedTopic ? ` — ${requestedTopic}` : (topicName && !syllabusText ? ` — ${topicName}` : "");
  const testId = await withTransaction(async (conn) => {
    const id = await tests.insert(conn, {
      title: `AI Practice: ${subject.name}${titleScope} (${b.difficulty})`,
      subjectId: subject.id,
      topicId,
      durationMinutes: b.durationMinutes,
      maxAttempts: 1,
      status: "published",
      userId: user.id,
      questionCount: requestedCount,
      difficulty: b.difficulty,
      sourceType: "AI_GENERATED",
    });
    await tests.replaceQuestions(conn, id, uniqueIds);
    return id;
  });
  return tests.present(await tests.getRaw(testId));
}

module.exports = {
  create,
  assignQuestions,
  publish,
  archive,
  list,
  get,
  generatePractice,
};
